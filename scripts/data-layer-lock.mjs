#!/usr/bin/env node
/**
 * Readable snapshot of how Paper calls Saleor.
 *
 *   pnpm data:lock           rewrite data-layer.lock.md
 *   pnpm data:lock --check   fail if the snapshot drifted
 *
 * The diff is the review surface for cost: a new cached loader or a new
 * mutation shows up here instead of hiding inside a component.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import prettier from "prettier";
import ts from "typescript";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "data-layer.lock.md");
const CALLS = new Set([
	"cachedQuery",
	"liveQuery",
	"sessionQuery",
	"mutate",
	"rawMutation",
	"bindCacheProfile",
]);

function walk(dir, acc = []) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		if (entry.name === "node_modules" || entry.name === ".next" || entry.name.startsWith(".")) continue;
		const path = join(dir, entry.name);
		if (entry.isDirectory()) walk(path, acc);
		// Tests are not the cost surface; only runtime call sites belong in the lock.
		else if (/\.tsx?$/.test(entry.name) && !/\.(d|test)\.tsx?$/.test(entry.name)) acc.push(path);
	}
	return acc;
}

function calleeName(node) {
	if (ts.isIdentifier(node)) return node.text;
	if (ts.isPropertyAccessExpression(node) && ts.isIdentifier(node.name)) return node.name.text;
	return null;
}

function firstArg(node) {
	const arg = node.arguments[0];
	if (!arg) return "";
	if (ts.isIdentifier(arg)) return arg.text;
	return "";
}

/** The `profile` argument, plus any flag that changes what gets cached. */
function profileArg(node, source) {
	const arg = node.arguments[1];
	if (!arg || !ts.isObjectLiteralExpression(arg)) return "";
	let profile = "";
	let allowsPartial = false;
	for (const prop of arg.properties) {
		if (!ts.isPropertyAssignment(prop)) continue;
		const name = ts.isIdentifier(prop.name) ? prop.name.text : "";
		if (name === "profile") profile = source.slice(prop.initializer.getStart(), prop.initializer.getEnd());
		if (name === "allowPartialData" && prop.initializer.kind === ts.SyntaxKind.TrueKeyword)
			allowsPartial = true;
	}
	return allowsPartial ? `${profile} (allows partial data)` : profile;
}

/**
 * Name of a function-like node, or null when it is anonymous.
 * `const load = async () => …` and `{ load() {} }` are named by their binding.
 */
function functionName(node) {
	if ((ts.isFunctionDeclaration(node) || ts.isMethodDeclaration(node)) && node.name) {
		return node.name.getText();
	}
	if (ts.isArrowFunction(node) || ts.isFunctionExpression(node)) {
		if (ts.isFunctionExpression(node) && node.name) return node.name.getText();
		// `const findCheckout = cache(async () => …)` is still `findCheckout`.
		let parent = node.parent;
		while (
			parent &&
			(ts.isCallExpression(parent) || ts.isParenthesizedExpression(parent) || ts.isAsExpression(parent))
		) {
			parent = parent.parent;
		}
		if (parent && (ts.isVariableDeclaration(parent) || ts.isPropertyAssignment(parent)))
			return parent.name.getText();
	}
	return null;
}

/** `outer.inner` for the named functions around a call. Line numbers are left out on purpose. */
function scopeOf(node) {
	const names = [];
	for (let current = node.parent; current; current = current.parent) {
		const name = functionName(current);
		if (name) names.unshift(name);
	}
	return names.length > 0 ? names.join(".") : "(module)";
}

const counts = new Map();
for (const file of walk(join(ROOT, "src"))) {
	if (file.includes(`${join("src", "lib", "saleor")}`)) continue;
	const text = readFileSync(file, "utf8");
	const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
	const rel = relative(ROOT, file);
	function visit(node) {
		if (ts.isCallExpression(node)) {
			const name = calleeName(node.expression);
			if (name && CALLS.has(name)) {
				const row = {
					file: rel,
					scope: scopeOf(node),
					call: name,
					target: firstArg(node),
					profile: profileArg(node, text),
				};
				const key = JSON.stringify(row);
				const seen = counts.get(key);
				if (seen) seen.count++;
				else counts.set(key, { ...row, count: 1 });
			}
		}
		ts.forEachChild(node, visit);
	}
	visit(source);
}

const rows = [...counts.values()].sort(
	(a, b) =>
		a.file.localeCompare(b.file) ||
		a.scope.localeCompare(b.scope) ||
		a.call.localeCompare(b.call) ||
		a.target.localeCompare(b.target) ||
		a.profile.localeCompare(b.profile),
);

const lines = [
	"# Data layer lock",
	"",
	"Generated by `pnpm data:lock`. Do not edit by hand.",
	"A diff here is a Saleor access or cache-profile change — review it for cost and freshness.",
	"Rows are keyed by file and enclosing function, not line, so formatting does not move them.",
	"",
	"| Call | Target | Profile | Where |",
	"| --- | --- | --- | --- |",
	...rows.map(
		(row) =>
			`| ${row.call}${row.count > 1 ? ` ×${row.count}` : ""} | ${row.target || "—"} | ${row.profile || "—"} | ${row.file} › ${row.scope} |`,
	),
	"",
];
const next = await prettier.format(`${lines.join("\n")}\n`, { filepath: OUT });

if (process.argv.includes("--check")) {
	const current = readFileSync(OUT, "utf8");
	if (current !== next) {
		console.error("data-layer.lock.md is stale. Run pnpm data:lock and commit the diff.");
		process.exit(1);
	}
	console.log(`data-layer.lock.md matches ${rows.length} call(s).`);
} else {
	writeFileSync(OUT, next);
	console.log(`Wrote data-layer.lock.md (${rows.length} calls).`);
}

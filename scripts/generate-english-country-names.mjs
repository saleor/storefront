/**
 * Regenerates src/checkout/lib/consts/english-country-names.ts from countries.ts
 * using this Node process's Intl DisplayNames (en-US).
 *
 * Run after editing the countries list:
 *   node scripts/generate-english-country-names.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const COUNTRIES_PATH = resolve(ROOT, "src/checkout/lib/consts/countries.ts");
const OUT_PATH = resolve(ROOT, "src/checkout/lib/consts/english-country-names.ts");

const source = readFileSync(COUNTRIES_PATH, "utf8");
const codes = [...source.matchAll(/"([A-Z]{2})"/g)].map((match) => match[1]);
const uniqueCodes = [...new Set(codes)];

if (uniqueCodes.length !== codes.length) {
	throw new Error("Duplicate country codes in countries.ts");
}

const displayNames = new Intl.DisplayNames("en-US", { type: "region" });
const entries = uniqueCodes.map((code) => {
	const name = displayNames.of(code);
	if (!name) {
		throw new Error(`Intl.DisplayNames returned nothing for ${code}`);
	}
	return `\t${code}: ${JSON.stringify(name)},`;
});

const file = `/**
 * Stable English country labels for checkout address selects.
 *
 * Do not use Intl.DisplayNames at render time — Node and browser ICU/CLDR
 * diverge (e.g. FK → "Falkland Islands" vs "Falkland Islands (Islas Malvinas)"),
 * which breaks SSR hydration.
 *
 * Generated by \`node scripts/generate-english-country-names.mjs\` from
 * \`countries.ts\` + Node Intl (\`en-US\`). Re-run after changing that list.
 */
export const ENGLISH_COUNTRY_NAMES = {
${entries.join("\n")}
} as const;

export type EnglishCountryCode = keyof typeof ENGLISH_COUNTRY_NAMES;
`;

writeFileSync(OUT_PATH, file);
console.log(`[generate-english-country-names] Wrote ${uniqueCodes.length} labels → ${OUT_PATH}`);
